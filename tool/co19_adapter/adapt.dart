// CLI entry point: filter co19 tests and generate manifest + test file.
//
// Each co19 category gets:
//   - manifest.json  (entries list + stats)
//   - co19_test.dart (reads manifest, creates tests dynamically)
//
// Source files are read at runtime from the co19 submodule — no embedding.
//
// Usage:
//   fvm dart tool/co19_adapter/adapt.dart [--co19-root <path>] <co19-subdir>
//
// Example:
//   fvm dart tool/co19_adapter/adapt.dart Language/Expressions

import 'dart:convert';
import 'dart:io';

import 'filter.dart';
import 'transformer.dart';

void main(List<String> args) {
  var co19Root = '../../third_party/co19';
  String? subDir;

  // Parse args.
  for (var i = 0; i < args.length; i++) {
    if (args[i] == '--co19-root' && i + 1 < args.length) {
      co19Root = args[++i];
    } else if (args[i] == '--help' || args[i] == '-h') {
      _printUsage();
      exit(0);
    } else if (!args[i].startsWith('-')) {
      subDir = args[i];
    }
  }

  if (subDir == null) {
    _printUsage();
    exit(1);
  }

  final inputDir = '$co19Root/$subDir';
  if (!Directory(inputDir).existsSync()) {
    print('Error: directory does not exist: $inputDir');
    exit(1);
  }

  print('Scanning $inputDir ...');

  // Phase 1: Filter.
  final report = scanDirectory(inputDir);
  print(report);

  // Phase 2: Check which included files can be transformed.
  final included =
      report.results.where((r) => r.status == FilterStatus.included).toList();

  final entries = <String>[];
  var transformFailed = 0;

  for (final result in included) {
    final file = File('$inputDir${result.path}');
    final source = file.readAsStringSync();
    // Only check if source can be transformed (no unsupported relative imports).
    // Actual transform happens at runtime in co19_runner.dart.
    if (transformSource(source) == null) {
      transformFailed++;
      continue;
    }
    // co19-relative path for runtime file reading.
    final relativePath = result.path.replaceFirst('/', '');
    entries.add('$subDir/$relativePath');
  }

  print('\nFilter + transform results:');
  print('  Included by filter: ${included.length}');
  print('  Valid entries: ${entries.length}');
  print('  Transform failed (relative imports): $transformFailed');

  if (entries.isEmpty) {
    print('\nNo tests to generate.');
    exit(0);
  }

  // Phase 3: Write manifest.json (with entries list for runtime).
  final safeName = subDir
      .replaceAll('/', '_')
      .replaceAll(RegExp(r'[^a-zA-Z0-9_]'), '')
      .toLowerCase();
  final outputDir = 'test/co19/$safeName';
  Directory(outputDir).createSync(recursive: true);

  final groupName = 'co19 $subDir';

  final manifest = {
    'generated_at': DateTime.now().toIso8601String(),
    'group': groupName,
    'subDir': subDir,
    'input_dir': inputDir,
    'stats': {
      'total_files': report.total,
      'included_by_filter': included.length,
      'valid_entries': entries.length,
      'transform_failed': transformFailed,
      'excluded': report.excluded,
      'skipped': report.skipped,
      'not_test': report.notTest,
    },
    'exclude_reasons': report.reasonCounts,
    'entries': entries,
  };

  final manifestFile = '$outputDir/manifest.json';
  File(manifestFile).writeAsStringSync(
      const JsonEncoder.withIndent('  ').convert(manifest));
  print('\nManifest: $manifestFile (${entries.length} entries)');

  // Phase 4: Generate test file.
  final testFile = '$outputDir/co19_test.dart';
  final testContent = _generateTestFile(safeName);
  File(testFile).writeAsStringSync(testContent);
  print('Test file: $testFile');
}

String _generateTestFile(String safeName) {
  return '''@Tags(['co19'])
import 'package:test/test.dart';

// Generated by co19_adapter — do not edit manually.

import '../_infrastructure/co19_runner.dart';

void main() {
  co19TestSuite(
    manifestPath: 'test/co19/$safeName/manifest.json',
  );
}
''';
}

void _printUsage() {
  print('Usage: fvm dart tool/co19_adapter/adapt.dart '
      '[--co19-root <path>] <co19-subdir>');
  print('');
  print('Options:');
  print('  --co19-root  Path to co19 root '
      '(default: ../../third_party/co19)');
  print('');
  print('Example:');
  print('  fvm dart tool/co19_adapter/adapt.dart Language/Expressions');
}
