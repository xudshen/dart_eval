// Transforms co19 test source files into dart_eval test format.
//
// Pipeline: rewrite imports → escape for embedding → generate test wrapper.

/// Regex matching co19 Expect import (various quote styles and path depths).
final _expectImportPattern =
    RegExp(r'''import\s+(['"])\.\.[\./]*Utils/expect\.dart\1\s*;''');

/// Regex matching co19 dynamic_check / static_type_helper imports.
final _utilImportPattern =
    RegExp(r'''import\s+(['"])\.\.[\./]*Utils/\w+\.dart\1\s*;''');

/// Regex matching any relative import (starts with . or ..).
final _relativeImportPattern =
    RegExp(r'''import\s+(['"])\.{1,2}/''');

/// Rewrite Expect imports and detect unsupported relative imports.
///
/// Returns the transformed source, or `null` if the file has relative
/// imports that can't be handled (e.g., local lib.dart).
String? transformSource(String source) {
  // Replace Expect import with package import.
  var result =
      source.replaceAll(_expectImportPattern, "import 'package:co19_expect/expect.dart';");

  // Remove dynamic_check / static_type_helper imports (not needed in dart_eval).
  result = result.replaceAll(_utilImportPattern, '// [co19_adapter] removed Utils import');

  // Check for remaining relative imports → can't transform.
  if (_relativeImportPattern.hasMatch(result)) {
    return null;
  }

  return result;
}

/// Escape source for embedding inside a Dart triple-quoted string (''').
///
/// Escapes: `\` → `\\`, `$` → `\$`, `'''` → `\'\'\'`.
String escapeForEmbedding(String source) {
  return source
      .replaceAll(r'\', r'\\')
      .replaceAll(r'$', r'\$')
      .replaceAll("'''", r"\'\'\'");
}

/// Generate a single test case wrapping [escapedSource].
///
/// [testName] is used as the test description.
String generateTestCase(String testName, String escapedSource) {
  return '''
    test('$testName', () {
      final plugin = Co19ExpectPlugin();
      final compiler = Compiler();
      compiler.addPlugin(plugin);
      final runtime = compiler.compileWriteAndLoad({
        'co19_test': {
          'main.dart': \'\'\'
$escapedSource
\'\'\'
        }
      });
      plugin.configureForRuntime(runtime);
      runtime.executeLib('package:co19_test/main.dart', 'main');
    });
''';
}

/// Generate a complete test file from a list of (testName, originalSource) pairs.
///
/// [groupName] is used as the top-level group description.
/// [testEntries] is a list of (testName, transformedSource) pairs.
String generateTestFile(
    String groupName, List<MapEntry<String, String>> testEntries) {
  final buf = StringBuffer();

  // Header.
  buf.writeln('// Generated by co19_adapter — do not edit manually.');
  buf.writeln('// ignore_for_file: unused_import');
  buf.writeln();
  buf.writeln("import 'package:dart_eval/dart_eval.dart';");
  buf.writeln("import 'package:test/test.dart';");
  buf.writeln();
  buf.writeln("import '../_infrastructure/expect_plugin.dart';");
  buf.writeln();
  buf.writeln('void main() {');
  buf.writeln("  group('$groupName', () {");

  for (final entry in testEntries) {
    final escaped = escapeForEmbedding(entry.value);
    buf.write(generateTestCase(entry.key, escaped));
  }

  buf.writeln('  });');
  buf.writeln('}');

  return buf.toString();
}
